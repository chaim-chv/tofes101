import { chromium } from 'playwright'
const b = await chromium.launch({ channel: 'chrome' })
const ctx = await b.newContext()
const p = await ctx.newPage()
p.on('requestfailed', r => console.log('FAIL', r.url(), r.failure()?.errorText))
p.on('response', r => { if (r.status() >= 400) console.log('HTTP', r.status(), r.url()) })
p.on('console', m => console.log('CONSOLE', m.type(), m.text().slice(0,200)))
await p.goto('http://localhost:3013/draft-test/', { waitUntil: 'networkidle' })
console.log('before reload h1:', await p.locator('h1').innerText())
await p.reload({ waitUntil: 'networkidle' })
await p.waitForTimeout(2000)
console.log('after reload h1:', await p.locator('h1').innerText().catch(e => 'ERR ' + e.message))
console.log('pre text:', (await p.locator('pre').innerText().catch(() => 'no pre')).slice(0,200))
console.log('scripts:', await p.evaluate(() => [...document.scripts].map(s => s.src).filter(Boolean)))
await b.close()
